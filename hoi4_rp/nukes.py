"""Nuclear strikes, for the chronicle: who struck which state, with what.

HOI4 fires on_nuke_drop for every nuke (ROOT the country that struck, FROM the state). write-mod adds an effect there
(airp_nukes_on_actions.txt): the state goes into the striking country's airp_nuked array. Each chronicle snapshot
reads those arrays and the stocks of the countries that hold or used nuclear weapons (script()); diff() turns new
entries into events, a salvo (strikes less than QUIET_HOURS apart) as one, told once the striker has paused that
long. The weapon is told by which stocks fell over the salvo: nuclear bombs, or nuclear missiles of their three
kinds ("nuclear weapons" when none fell, as when the factories made more meanwhile).
The arrays are never cleared: an earlier save holds them as they were then, and so do its snapshots.
"""

from __future__ import annotations

import os
from collections import defaultdict
from typing import Dict, List, Tuple

ARRAY = "airp_nuked"
QUIET_HOURS = 24        # strikes this close together are one salvo, told when the striker has been quiet this long
MAX_PLACES = 8          # states named in one event; the rest are counted
# by the game's own names, the longest range first: when several stocks fell, the most telling is named
MISSILES = [("nuclear_missile_equipment_2", "an intercontinental nuclear missile"),
            ("nuclear_missile_equipment_1", "a medium range nuclear missile"),
            ("nuclear_missile_equipment", "a nuclear ballistic missile")]

_HOLDS = " ".join(f"has_equipment = {{ {k} > 0 }}" for k, _ in MISSILES)


def script() -> str:
    """For the snapshot query. Missile counts only while some country holds missiles: reading them makes the game
    warn of a dynamic token on every read (has_equipment doesn't)."""
    from . import bridge
    try:
        missiles = bridge.trigger(f"any_country = {{ OR = {{ {_HOLDS} }} }}")
    except bridge.BridgeError:
        missiles = False
    counts = "|".join(f"[?THIS.num_equipment@{k}]" if missiles else "0" for k, _ in MISSILES)
    return (f'every_country = {{ limit = {{ OR = {{ num_of_nukes > 0 {_HOLDS} '
            f'check_variable = {{ {ARRAY}^num > 0 }} }} }} '
            f'log = "NS|[THIS.GetTag]|[?THIS.num_of_nukes]|{counts}" '
            f'for_each_scope_loop = {{ array = {ARRAY} '
            f'log = "NK|[PREV.GetTag]|[THIS.GetID]|[THIS.GetName]|[THIS.Owner.GetTag]|[THIS.Controller.GetTag]" }} }} ')

_ON_ACTIONS = f"""# GENERATED by hoi4_rp/nukes.py. Don't edit by hand.
# ROOT struck the state FROM with a nuke: remembered for the chronicle (hoi4_rp/nukes.py reads it)
on_actions = {{
	on_nuke_drop = {{
		effect = {{
			add_to_array = {{ {ARRAY} = FROM }}
		}}
	}}
}}
"""


def files(mod_dir: str) -> Dict[str, Tuple[str, str]]:
    return {os.path.join(mod_dir, "common", "on_actions", "airp_nukes_on_actions.txt"): (_ON_ACTIONS, "utf-8")}


def _num(x: str) -> float:
    try:
        return float(x)
    except ValueError:
        return 0.0


def read(lines: List[str], snap: Dict) -> None:
    """Into a snapshot: "nukes" {tag: [[state id, name, owner, controller], ...]} in the order struck, and
    "nuke_stock" {tag: [bombs, missiles of each kind in MISSILES' order]}."""
    struck: Dict[str, List[List[str]]] = defaultdict(list)
    stock: Dict[str, List[float]] = {}
    for line in lines:
        kind, _, rest = line.partition("|")
        f = [x.strip() for x in rest.split("|")]
        if kind == "NK" and len(f) >= 5:
            struck[f[0]].append(f[1:5])
        elif kind == "NS" and len(f) >= 2 + len(MISSILES):
            stock[f[0]] = [_num(x) for x in f[1:2 + len(MISSILES)]]
    snap["nukes"], snap["nuke_stock"] = dict(struck), stock


def _hours(a: str, b: str) -> float:
    """Game hours from date key a to b ('1944.05.03.13')."""
    from datetime import datetime
    t = lambda k: datetime(*(int(x) for x in (k.split(".") + ["0"] * 4)[:4]))
    try:
        return (t(b) - t(a)).total_seconds() / 3600
    except ValueError:
        return QUIET_HOURS


def _weapon(old: List[float], new: List[float], n: int) -> str:
    """What `n` strikes were made with, from the stock before and after: each kind whose stock fell."""
    old, new = old or [0.0] * (1 + len(MISSILES)), new or [0.0] * (1 + len(MISSILES))
    kinds = [words for i, (_, words) in enumerate(MISSILES) if new[1 + i] < old[1 + i]]
    if new[0] < old[0] or not kinds and not any(old[1:]) and not any(new[1:]):   # no missiles at all: bombs
        kinds.append("a nuclear bomb")
    if not kinds:
        kinds = ["a nuclear weapon"]
    if n == 1:
        return kinds[0]
    many = [k.split(" ", 1)[1].replace("missile", "missiles").replace("bomb", "bombs").replace("weapon", "weapons")
            for k in kinds]
    return many[0] if len(many) == 1 else ", ".join(many[:-1]) + " and " + many[-1]


def events(old: Dict, new: Dict, name, add) -> None:
    """The strikes of a salvo told as one: a striker's new strikes wait until it has struck nothing more for
    QUIET_HOURS, then become one event per country struck (add(tags, text, kind, world)). What is waiting is carried
    from snapshot to snapshot (nukes_told: strikes told per striker; nukes_last: when it last struck; nukes_from:
    when the salvo began and its stock then). An older snapshot without nukes: nothing to compare."""
    if "nukes" not in old:
        return
    from .campaign import date_words
    now = new["date"]
    told = dict(old["nukes_told"] if "nukes_told" in old else {t: len(r) for t, r in old["nukes"].items()})
    last, began = dict(old.get("nukes_last", {})), dict(old.get("nukes_from", {}))
    strikes = new.get("nukes", {})
    for tag in set(strikes) | set(told):
        n, before = len(strikes.get(tag, [])), len(old["nukes"].get(tag, []))
        if n < told.get(tag, 0):                           # an earlier save: those strikes never happened
            told[tag] = n
            last.pop(tag, None)
            began.pop(tag, None)
        elif n > before:
            if tag not in began:   # a new salvo: first seen now (not the last snapshot's date: it may be months
                began[tag] = [now, old.get("nuke_stock", {}).get(tag)]     # back), and the stock before it
            last[tag] = now
    for tag, rows in strikes.items():
        if len(rows) <= told.get(tag, 0) or _hours(last.get(tag, now), now) < QUIET_HOURS:
            continue
        fresh = rows[told.get(tag, 0):]
        start, stock = began.pop(tag, [now, None])
        end = last.pop(tag, now)
        told[tag] = len(rows)
        weapon = _weapon(stock, new.get("nuke_stock", {}).get(tag), len(fresh))
        when = date_words(start) if start[:10] == end[:10] else f"between {date_words(start)} and {date_words(end)}"
        by_owner: Dict[str, List[List[str]]] = defaultdict(list)
        for r in fresh:
            by_owner[r[2]].append(r)
        for owner, hit in by_owner.items():
            places = list(dict.fromkeys(r[1] for r in hit))
            shown = places[:MAX_PLACES] + ([f"{len(places) - MAX_PLACES} more"] if len(places) > MAX_PLACES else [])
            where = shown[0] if len(shown) == 1 else ", ".join(shown[:-1]) + " and " + shown[-1]
            times = f" ({len(hit)} strikes)" if len(hit) > 1 else ""
            held = sorted({r[3] for r in hit} - {owner, ""})
            whose = "its own land" if owner == tag else f"{name(owner)}'s land"
            if held:
                whose += f", held by {', '.join(name(t) for t in held)}"
            # which weapon fell where is not known: with several countries struck, the salvo's weapons are named
            arms = f"in a salvo of {weapon}" if len(by_owner) > 1 else f"with {weapon}"
            text = f"{name(tag)} struck {where} ({whose}) {arms}{times}, {when}."
            add(list(dict.fromkeys([tag, owner] + held)), text, "nuke", True)
    new["nukes_told"], new["nukes_last"], new["nukes_from"] = told, last, began
