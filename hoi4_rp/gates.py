"""Switching off parts of the game AI's own diplomacy, one setting at a time ([ai_diplomacy] guarantees, factions =
game | ours; default game).

HOI4 gates each diplomatic action with a scripted trigger, DIPLOMACY_<ACTION>_ENABLE_TRIGGER (ROOT acts, FROM is the
target). write-mod writes the one in force (the game's, or a mod's with its own rules, found through the enabled mods)
again with one condition in front, in a file loaded last (zzz_airp_<setting>.txt): an AI country may not use the
action while the setting's global flag is set. `run` sets or clears the flags from config after loading, so a
setting needs no new mod. Script effects (focuses, events, decisions, our deals) aren't gated; the player's own
buttons stay.

    guarantees   the Guarantee action (guarantees.py; the storyteller gives the world its guarantees)
    factions     inviting into a faction, asking to join one, expelling a member, leaving (factions.py; the
                 storyteller forms and breaks the world's factions)
    wars         justifying a war goal, except on a country in the justifier's airp_justify array (wars.py; the
                 storyteller lets a country prepare a war). Declaring war itself has no such trigger: the bridge
                 stops it (bridge.wars, set by wars.sync)
"""

from __future__ import annotations

import os
import re
from typing import Dict, List, Tuple

GATES: Dict[str, Tuple[str, List[str], str]] = {
    "guarantees": ("airp_ai_guarantees_off", ["DIPLOMACY_GUARANTEE_ENABLE_TRIGGER"],
                   "Guarantees between AI countries are made by agreement"),
    "factions": ("airp_ai_factions_off", ["DIPLOMACY_OFFER_JOIN_FACTION_ENABLE_TRIGGER",
                                          "DIPLOMACY_JOIN_FACTION_ENABLE_TRIGGER",
                                          "DIPLOMACY_KICK_FROM_FACTION_ENABLE_TRIGGER",
                                          "DIPLOMACY_LEAVE_FACTION_ENABLE_TRIGGER"],
                 "Factions between AI countries are made by agreement"),
    "wars": ("airp_ai_wars_off", ["DIPLOMACY_GENERATE_WARGOAL_ENABLE_TRIGGER"],
             "Governments prepare their wars by decision"),
}
# A condition more, for a gate that lets some actions through: the target is in the actor's array
EXCEPT = {"wars": "NOT = { is_in_array = { airp_justify = FROM } }"}


def ours(setting: str) -> bool:
    """Does our system, not the game's AI, handle this part of diplomacy (config)?"""
    from .config import settings
    return getattr(settings().ai, setting, "game") == "ours"


def _definition(name: str) -> Tuple[str, str]:
    """The body of the scripted trigger `name` the game uses (the last one loaded) and the file it is in."""
    from . import gamefiles
    body, source = "", ""
    for path in gamefiles.files("common/scripted_triggers"):
        if os.path.basename(path).lower().startswith("zzz_airp_"):
            continue                                        # ours, from an earlier write-mod
        with open(path, encoding="utf-8-sig", errors="replace") as f:
            text = re.sub(r"#[^\n]*", "", f.read())
        for m in re.finditer(rf"(?m)^\s*{name}\s*=\s*\{{", text):
            depth, i = 1, m.end()
            while i < len(text) and depth:
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            body, source = text[m.end():i - 1].strip("\n"), path
    return body, source


def switch() -> None:
    """Set or clear each gate's flag as config says (after loading: a save holds the flags as they were)."""
    from . import actions
    for setting, (flag, _, _) in GATES.items():
        on = ours(setting)
        actions._effect(f"{'set' if on else 'clr'}_global_flag = {flag}")
        print(f"  [{setting}] the game's AI {'may not' if on else 'may'} act on its own")
    # declaring war has no trigger to gate: the bridge's veto, with the pairs allowed now (wars.sync)


def _cooldown(trigger: str) -> str:
    """The condition a dropped tie's cooldown puts in front of `trigger` (cooldowns.py), for everyone, the player
    included ('' if none)."""
    from . import cooldowns
    cond = cooldowns.TRIGGERS.get(trigger)
    return (f"\tif = {{\n\t\tlimit = {{ {cond} }}\n"
            f"\t\tcustom_trigger_tooltip = {{ tooltip = {cooldowns.TOOLTIP} always = no }}\n\t}}\n") if cond else ""


def files(mod_dir: str) -> Dict[str, Tuple[str, str]]:
    from . import cooldowns
    out, loc = {}, ["l_english:"]
    gated = set()
    for setting, (flag, triggers, tooltip) in GATES.items():
        parts = [f"# GENERATED by hoi4_rp/gates.py. Don't edit by hand.\n"
                 f"# The game's AI may not take these actions while {flag} is set ([ai_diplomacy] {setting} = ours);\n"
                 f"# the rest of each is the trigger in force.\n"]
        for trigger in triggers:
            body, source = _definition(trigger)
            gated.add(trigger)
            parts.append(f"# from {source or 'nowhere (none found)'}\n"
                         f"{trigger} = {{\n"
                         f"\tif = {{\n\t\tlimit = {{ has_global_flag = {flag} is_ai = yes {EXCEPT.get(setting, '')}}}\n"
                         f"\t\tcustom_trigger_tooltip = {{ tooltip = {flag}_tt always = no }}\n\t}}\n"
                         f"{_cooldown(trigger)}{body}\n}}\n")
        out[os.path.join(mod_dir, "common", "scripted_triggers", f"zzz_airp_{setting}.txt")] = ("\n".join(parts), "utf-8")
        loc.append(f' {flag}_tt:0 "{tooltip}"')
    # the cooldowns' other triggers, each in front of the trigger in force (if the game has one)
    parts = ["# GENERATED by hoi4_rp/gates.py. Don't edit by hand.\n"
             "# A tie a deal ended is not made again for a while (cooldowns.py); the rest of each is the trigger in "
             "force.\n"]
    for trigger in cooldowns.TRIGGERS:
        if trigger not in gated:
            body, source = _definition(trigger)
            parts.append(f"# from {source or 'nowhere (none found)'}\n{trigger} = {{\n{_cooldown(trigger)}{body}\n}}\n")
    out[os.path.join(mod_dir, "common", "scripted_triggers", "zzz_airp_cooldowns.txt")] = ("\n".join(parts), "utf-8")
    loc.append(f' {cooldowns.TOOLTIP}:0 "{cooldowns.TOOLTIP_TEXT}"')
    out[os.path.join(mod_dir, "localisation", "english", "airp_gates_l_english.yml")] = ("\n".join(loc) + "\n",
                                                                                       "utf-8-sig")
    return out
