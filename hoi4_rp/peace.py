def member_peace() -> bool:
    """[letters] member_peace: the player may make peace for their whole faction, leader or not."""
    from .config import settings
    return settings().letters.member_peace


def possible(me: str, other: str) -> bool:
    """Peace can be made between the two right now (see the module notes)."""
    member = " is_ai = no" if member_peace() else ""             # the player, a faction member: for all of it
    side = lambda enemy: (f"is_subject = no OR = {{ is_faction_leader = yes is_in_faction = no{member} }} "
                          f"NOT = {{ civilwar_target = {enemy} }}")
    return bridge.trigger(f"{me} = {{ has_war_with = {other} {side(other)} {other} = {{ {side(me)} }} }}")


def blocker(me: gamestate.CountryState, them: gamestate.CountryState) -> str:
    """Why the two can't make peace right now, in words for the other side (empty if they can, or aren't at war)."""
    if me.tag not in them.enemies:
        return ""
    for x in (them, me):
        # In a faction, its leader makes peace for all (a subject's overlord may itself be a mere member, or beaten);
        # with member_peace the player (`me`) may make it for theirs
        if x.faction and x.faction_leader and x.faction_leader != x.tag and not (x is me and member_peace()):
            return (f"{x.name} fights as a member of the {x.faction}, so peace can only come through its leader, "
                    f"{x.name_of(x.faction_leader)}")
        if x.overlord:
            return (f"{x.name} is a subject of {x.name_of(x.overlord)}, so peace between you can only come through "
                    f"{x.name_of(x.overlord)}")
    if bridge.trigger(f"{me.tag} = {{ OR = {{ civilwar_target = {them.tag} {them.tag} = {{ civilwar_target = {me.tag} }} }} }}"):
        return "this is a civil war: it ends only when one side is gone"
    return ""


def estimate(me: gamestate.CountryState, them: gamestate.CountryState,
             player_leads: bool = True) -> Tuple[float, str]:
    """(`me`'s share of the conference score, negative = the other side's; the line for the offer). `me` is the
    player unless `player_leads` is False (two AI countries: aipeace.py)."""
    whole = gamestate.whole_war(me, them)
    if whole:                                   # factions at war: the whole war counts, not the two leaders alone
        margin = whole["favour"]
        sides = (" (both sides' allies come to the conference"
                 + ("; on our side we alone make the demands)" if player_leads else ")"))
    else:
        margin = gamestate._war_score(them, me) - gamestate._war_score(me, them)
        sides = ""
    margin = max(-1.0, min(1.0, margin))
    pct = round(abs(margin) * 100)
    if pct == 0:
        return 0.0, f"Outcome: a white peace (neither side gains anything){sides}."
    if margin > 0:
        return margin, f"Outcome: our side receives {pct}% of the war score at the peace conference{sides}."
    return margin, f"Outcome: {them.name}'s side receives {pct}% of the war score at the peace conference{sides}."


def table(me: gamestate.CountryState, them: gamestate.CountryState) -> str:
    """Who a peace between the two brings to the conference, in words for `them` (empty between two countries
    alone)."""
    mine, theirs = gamestate.war_side(them, me), gamestate.war_side(me, them)
    if len(mine) == 1 and len(theirs) == 1:
        return ""
    name = lambda t: them.name if t == them.tag else me.name if t == me.tag else them.name_of(t)
    fallen = lambda side: [name(t) for t in side if t in them.fallen]
    out = (f"A peace between you ends the war for both sides at once: your {len(mine)} countries and their "
           f"{len(theirs)} all come to the one peace conference, the capitulated among them too")
    lost = fallen(mine) + fallen(theirs)
    return (out + (f" ({', '.join(lost)} capitulated: their fate is decided there)" if lost else "")
            + f". On {me.name}'s side, {me.name} alone makes the demands: its allies take nothing it doesn't give "
              f"them, so what you agree with {me.name} holds for its whole side.")


def make(me: str, other: str, player_leads: bool = True) -> Optional[str]:
    """Start the peace conference, scored now. Returns the outcome line, or None if it couldn't be started.
    `player_leads`: `me` is the player, whose AI allies demand nothing (_AI_PEACE); between two AI countries
    (aipeace.py) both sides' members make their own demands, as in any conference the game runs."""
    try:
        a, b = gamestate.country(me), gamestate.country(other)
    except gamestate.StateError as e:
        print("  peace: could not read the countries:", e)
        return None
    margin, line = estimate(a, b, player_leads)
    # Checked in game: the scope country is the winner and `tag` the loser (whatever ROOT is).
    winner, loser = (me, other) if margin >= 0 else (other, me)
    # Our demand costs (_COSTS) apply to everyone at the table: both sides, their faction members and subjects.
    flag = (f"set_country_flag = {FLAG} every_faction_member = {{ set_country_flag = {FLAG} }} "
            f"every_subject_country = {{ set_country_flag = {FLAG} }}")
    # The player (`me`) leads their side: their AI allies and subjects take nothing (_AI_PEACE) and hand the player
    # their share of the score (SCORE). FACTION brings each side's whole faction even when its country at the table
    # is a mere member (member_peace), where the default brings a faction only with its leader.
    follow = (f"every_country = {{ limit = {{ NOT = {{ tag = {me} }} OR = {{ is_in_faction_with = {me} "
              f"is_subject_of = {me} }} }} set_country_flag = {FOLLOW} "
              f"add_dynamic_modifier = {{ modifier = {SCORE} }} }}") if player_leads else ""
    scopes = f"set_country_flag = {FACTION_SCOPE} " if player_leads else ""
    # started by EVENT within the game hour, not here inside the frame (see _EVENTS)
    reply = bridge.send(f"eval_effect {winner} = {{ {follow} {flag} {scopes}"
                        f"set_variable = {{ {SCORE_VAR} = {abs(margin):.3f} }} "
                        f"{loser} = {{ {flag} set_variable = {{ {WINNER_VAR} = {winner} }} "
                        f"country_event = {{ id = {EVENT} hours = 1 }} }} }}")[0]
    if not reply.startswith("OK"):
        print("  peace failed:", reply)
        return None
    print(f"  peace conference: {winner} wins over {loser}, score {abs(margin):.3f} (starts within the hour)")
    return line
